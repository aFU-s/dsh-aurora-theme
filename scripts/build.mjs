#!/usr/bin/env node
/**
 * Build dsh-aurora-theme's published artifacts from src/.
 *
 * No bundler and no dependencies: the two halves need nothing more than a file
 * copy and one wrapper.
 *
 *   lib/index.js   the host half, copied verbatim from src/host.js
 *   lib/client.js  the browser half, wrapped in the harness client-bundle
 *                  contract that @deepseek-ai/dsh-client-modules serves at
 *                  /plugins/<row-id>/client.js:
 *
 *                    window.__ModuleLoader__.load({
 *                      id: "<package name>",
 *                      factory: (require) => { ...; return module.exports }
 *                    })
 *
 *                  `require` resolves against the runtime module table — a seed
 *                  word such as `react`, or a module registered by another
 *                  plugin bundle. The body therefore stays CommonJS.
 *
 * The render functions are exported so scripts/smoke.mjs can assert that the
 * committed lib/ matches src/ — lib/ is committed on purpose, because a git
 * install has no build step and pnpm blocks lifecycle scripts.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

export const BANNER = '/* GENERATED by scripts/build.mjs from src/ — do not edit by hand. */\n';

/** The host half is a plain ESM module; it only gets a generated banner. */
export function renderHost(hostSource) {
  if (/^\s*import\s/m.test(hostSource) || /require\(/.test(hostSource)) {
    throw new Error('build: src/host.js must be dependency-free ESM (no imports, no require)');
  }
  return BANNER + hostSource;
}

/** Wrap the CommonJS browser half in the runtime's module-loader contract. */
export function renderClient(packageName, clientSource) {
  if (/^\s*(import|export)\s/m.test(clientSource)) {
    throw new Error('build: src/client.js must be CommonJS — the bundle factory supplies require/exports');
  }
  const indented = clientSource
    .split('\n')
    .map((line) => (line === '' ? '' : '\t\t' + line))
    .join('\n');
  return (
    BANNER +
    `window.__ModuleLoader__.load({
\tid: ${JSON.stringify(packageName)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${indented}
\t\treturn module.exports;
\t}
});
`
  );
}

function main() {
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  const host = renderHost(readFileSync(join(ROOT, 'src', 'host.js'), 'utf8'));
  const client = renderClient(pkg.name, readFileSync(join(ROOT, 'src', 'client.js'), 'utf8'));

  mkdirSync(join(ROOT, 'lib'), { recursive: true });
  writeFileSync(join(ROOT, 'lib', 'index.js'), host);
  writeFileSync(join(ROOT, 'lib', 'client.js'), client);

  console.log('build: lib/index.js  ' + host.length + ' bytes');
  console.log('build: lib/client.js ' + client.length + ' bytes');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
